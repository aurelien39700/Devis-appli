-- Schéma PostgreSQL de l'application SOMEPRE (suivi d'affaires et devis).
-- Idempotent : exécuté à chaque démarrage du serveur.
--
-- Les identifiants historiques (Date.now() du JSON) sont conservés tels quels
-- en BIGINT ; les nouveaux viennent de la séquence, recalée au-dessus du
-- maximum après la migration. L'API les renvoie en texte, comme avant.

CREATE TABLE IF NOT EXISTS users (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        TEXT NOT NULL UNIQUE,
    password    TEXT NOT NULL
);
-- droit admin donné à un compte nominatif (ajouté après la mise en service)
ALTER TABLE users ADD COLUMN IF NOT EXISTS is_admin BOOLEAN NOT NULL DEFAULT FALSE;

CREATE TABLE IF NOT EXISTS clients (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        TEXT NOT NULL,
    adresse     TEXT NOT NULL DEFAULT '',
    tva         TEXT NOT NULL DEFAULT ''
);

-- Interlocuteurs d'un client. L'id est fabriqué par le front (texte libre).
CREATE TABLE IF NOT EXISTS contacts (
    id          TEXT PRIMARY KEY,
    client_id   BIGINT NOT NULL REFERENCES clients(id) ON DELETE CASCADE,
    position    INT NOT NULL DEFAULT 0,
    nom         TEXT NOT NULL,
    fonction    TEXT NOT NULL DEFAULT '',
    email       TEXT NOT NULL DEFAULT '',
    tel         TEXT NOT NULL DEFAULT ''
);
CREATE INDEX IF NOT EXISTS contacts_client_idx ON contacts(client_id);

CREATE TABLE IF NOT EXISTS postes (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          TEXT NOT NULL,
    taux_horaire  NUMERIC,
    is_machine    BOOLEAN NOT NULL DEFAULT FALSE,
    ordre         INT
);

CREATE TABLE IF NOT EXISTS affaires (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         TEXT NOT NULL,
    client_id    BIGINT REFERENCES clients(id) ON DELETE SET NULL,
    description  TEXT NOT NULL DEFAULT '',
    statut       TEXT NOT NULL DEFAULT 'en_cours'
                 CHECK (statut IN ('brouillon','envoye','en_cours','terminee','archivee')),
    -- coefficient de marge sur les heures, pour une affaire sans devis
    coeff_regie  NUMERIC
);
CREATE INDEX IF NOT EXISTS affaires_client_idx ON affaires(client_id);
CREATE INDEX IF NOT EXISTS affaires_statut_idx ON affaires(statut);

-- Heures pointées. entered_by garde le nom saisi à l'époque ; user_id le
-- relie au compte quand il existe (le nom affiché suit alors le compte).
CREATE TABLE IF NOT EXISTS entries (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    affaire_id  BIGINT NOT NULL REFERENCES affaires(id) ON DELETE CASCADE,
    poste_id    BIGINT REFERENCES postes(id) ON DELETE SET NULL,
    user_id     BIGINT REFERENCES users(id) ON DELETE SET NULL,
    entered_by  TEXT NOT NULL DEFAULT '',
    hours       NUMERIC NOT NULL DEFAULT 0,
    date        TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS entries_affaire_idx ON entries(affaire_id);
CREATE INDEX IF NOT EXISTS entries_user_date_idx ON entries(user_id, date);

-- Un devis par affaire.
CREATE TABLE IF NOT EXISTS devis (
    affaire_id        BIGINT PRIMARY KEY REFERENCES affaires(id) ON DELETE CASCADE,
    -- libellés saisis sur le devis (peuvent différer de la fiche affaire/client)
    client            TEXT NOT NULL DEFAULT '',
    affaire           TEXT NOT NULL DEFAULT '',
    num_commande      TEXT NOT NULL DEFAULT '',
    date              DATE NOT NULL DEFAULT CURRENT_DATE,
    coeff_marge       NUMERIC NOT NULL DEFAULT 1.2,
    note_client       TEXT NOT NULL DEFAULT '',
    delai             TEXT NOT NULL DEFAULT '',
    reglement         TEXT NOT NULL DEFAULT 'virement_45j',
    echeances         JSONB NOT NULL DEFAULT '[]',
    interlocuteur_id  TEXT NOT NULL DEFAULT '',
    token             TEXT UNIQUE,
    reponse_action    TEXT CHECK (reponse_action IN ('accepte','refuse')),
    reponse_date      TIMESTAMPTZ,
    reponse_motif     TEXT,
    created_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Lignes d'un devis :
--   travail : nom, taux, semaines (tableau d'heures par semaine)
--   machine : nom, taux, temps
--   achat   : nom, fournisseur, quantite, prix_unit
CREATE TABLE IF NOT EXISTS devis_lignes (
    id           BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    affaire_id   BIGINT NOT NULL REFERENCES devis(affaire_id) ON DELETE CASCADE,
    type         TEXT NOT NULL CHECK (type IN ('travail','machine','achat')),
    position     INT NOT NULL,
    nom          TEXT NOT NULL DEFAULT '',
    taux         NUMERIC,
    semaines     JSONB,
    temps        NUMERIC,
    fournisseur  TEXT,
    quantite     NUMERIC,
    prix_unit    NUMERIC
);
CREATE INDEX IF NOT EXISTS devis_lignes_devis_idx ON devis_lignes(affaire_id, type, position);

-- Achats et fournitures réellement faits sur une affaire (le devis, lui,
-- garde les achats prévus).
CREATE TABLE IF NOT EXISTS affaire_achats (
    id           BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    affaire_id   BIGINT NOT NULL REFERENCES affaires(id) ON DELETE CASCADE,
    position     INT NOT NULL,
    nom          TEXT NOT NULL DEFAULT '',
    fournisseur  TEXT NOT NULL DEFAULT '',
    quantite     NUMERIC NOT NULL DEFAULT 0,
    prix_unit    NUMERIC NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS affaire_achats_affaire_idx ON affaire_achats(affaire_id, position);

-- Bibliothèques de libellés proposés dans le devis.
CREATE TABLE IF NOT EXISTS fournisseurs (
    position  INT NOT NULL,
    nom       TEXT PRIMARY KEY
);
CREATE TABLE IF NOT EXISTS achats_biblio (
    position  INT NOT NULL,
    nom       TEXT PRIMARY KEY
);

-- Coordonnées de l'entreprise (une seule ligne).
CREATE TABLE IF NOT EXISTS entreprise (
    id       INT PRIMARY KEY DEFAULT 1 CHECK (id = 1),
    nom      TEXT,
    forme    TEXT,
    adresse  TEXT,
    cp       TEXT,
    ville    TEXT,
    tel      TEXT,
    site     TEXT,
    siret    TEXT,
    tva      TEXT,
    logo     TEXT
);
